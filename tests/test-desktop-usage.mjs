import assert from 'node:assert/strict';
import { normalizeDesktopUsage, DesktopUsageReader } from '../lib/desktop-usage.js';
const now = Date.parse('2026-11-02T12:00:00Z');
const loomy = normalizeDesktopUsage({ status: 'signed-in', account: '138****12', points: { permanent: 100, daily: 0, updatedAt: '2026-11-01T12:00:00Z' }, session: 'SECRET', models: [{ key: 'SECRET' }] }, 'loomy', now);
assert.deepEqual(loomy.windows, []);
assert.equal(loomy.linkedAccounts.length, 1);
assert.equal(loomy.freshness, 'stale');
assert.equal(loomy.lastSuccessAt, '2026-11-01T12:00:00.000Z');
assert(loomy.extras.some(row => row.value === '每日赠送积分：0'));
assert(!loomy.extras.some(row => row.kind === 'balance'), '独立余额池不合成 API 没有的总余额');
assert(!('accountId' in loomy) && !('accountActive' in loomy), '没有公开账号身份时不伪造 ID 或模式');
assert(!JSON.stringify(loomy).includes('SECRET'));
const raccoon = normalizeDesktopUsage({ status: 'signed-in', nickname: 'alice@example.test', expiresAt: now - 1000, points: { total: 0, plan: 'Pro', note: 'SECRET' }, probeKey: 'SECRET', refreshToken: 'SECRET' }, 'raccoon', now);
assert.equal(raccoon.account, 'a***@example.test');
assert.equal(raccoon.authStatus, 'expired');
assert.equal(raccoon.freshness, 'unknown');
assert(!('lastSuccessAt' in raccoon));
assert(raccoon.extras.some(row => row.kind === 'balance' && row.value === '0 积分'));
assert(!JSON.stringify(raccoon).includes('SECRET'));
assert.equal(normalizeDesktopUsage({ status: 'signed-out' }, 'raccoon', now), null);
assert(!normalizeDesktopUsage({ status: 'signed-in', points: {} }, 'raccoon', now).extras.some(row => row.kind === 'balance'));
let reads = 0, ready = false;
const reader = new DesktopUsageReader({ now: () => now, readJson: async (plugin, endpoint, query) => { reads++; assert.equal(plugin, 'loomy'); assert.equal(endpoint, 'status'); assert.deepEqual(query, {}, 'force 不调用 Loomy refresh=1'); return ready ? { status: 'signed-in', points: { daily: 20, permanent: 30 } } : undefined; } });
assert.equal(await reader.read('loomy'), undefined); ready = true;
await Promise.all([reader.read('loomy'), reader.read('loomy')]);
assert.equal(reads, 2, '缺席不缓存，在途合并');
await reader.read('loomy'); assert.equal(reads, 2);
await reader.read('loomy', true); assert.equal(reads, 3);
reader.dispose(); await assert.rejects(reader.read('loomy'), /卸载/);
console.log('PASS 独立Raccoon/Loomy：公开状态、单当前账号、缓存时间、秘密剔除与缺席恢复');
