import assert from "node:assert/strict";
import { loadHostModule } from "./helpers.mjs";
const { SubUsageService, normalizeZai, normalizeSynthetic, normalizeNanoGpt } = await loadHostModule();
const ids = ["zai-coding", "synthetic", "nanogpt"];
const reset = Date.parse("2026-10-05T00:00:00Z");
const quota = { active: true, state: "active", limits: { dailyInputTokens: 100, weeklyInputTokens: 600 }, dailyInputTokens: { used: 25, percentUsed: .25, resetAt: reset }, weeklyInputTokens: { used: 600, percentUsed: 1, resetAt: reset } };
let out = normalizeNanoGpt(quota);
assert.equal(out.windows[0].percent, 25); assert.equal(out.windows[0].kind, "day");
assert.equal(out.windows[0].cascade, true); assert.equal(out.windows[0].resetsAt, new Date(reset).toISOString());
assert.equal(out.windows[0].detail.unit, "tokens"); assert.equal(out.coverage, "complete");
out = normalizeNanoGpt({ ...quota, dailyInputTokens: { degraded: true, used: null, percentUsed: null } });
assert.equal(out.windows.length, 1); assert.equal(out.coverage, "partial");
assert.equal(normalizeNanoGpt({ ...quota, active: false, state: "inactive" }).windows.length, 0);
assert.equal(normalizeNanoGpt({ active: true, state: "active" }).coverage, "partial");
assert.equal(normalizeNanoGpt({ active: true, state: "active", tokens: { used: 50, percentUsed: .5, resetAt: reset }, tokenLimits: { total: 100 } }).windows[0].kind, "period");
assert.throws(() => normalizeNanoGpt({ active: true }));
out = normalizeSynthetic({ subscription: { requests: 27, limit: 135, renewsAt: new Date(reset).toISOString() }, search: { requests: 999 } });
assert.equal(out.windows.length, 1); assert.equal(out.windows[0].percent, 20); assert.equal(out.windows[0].detail.unit, "requests");
for (const limit of [0, -1, "135", null]) assert.throws(() => normalizeSynthetic({ subscription: { requests: 0, limit } }));
assert.equal(normalizeZai({ data: { limits: [{ type: "TOKENS_LIMIT", percentage: 12 }] } }).windows[0].kind, "5h");
assert.equal(normalizeZai({ data: { limits: [{ type: "TOKENS_LIMIT", unit: 6, percentage: 100, currentValue: 100, usage: 100 }, { type: "TOKENS_LIMIT", unit: 3, percentage: 10 }] } }).windows[1].cascade, true);
const files = new Map(), calls = [];
let now = reset - 10000, rateLimit = false;
const io = { readFileSync(path) { if (!files.has(path)) throw Object.assign(new Error("missing"), { code: "ENOENT" }); return files.get(path); }, mkdirSync() {}, chmodSync() {}, writeFileSync(path, data) { files.set(path, data); }, renameSync(from, to) { files.set(to, files.get(from)); files.delete(from); } };
const service = new SubUsageService({ effect() {}, llm: { listProviders: () => [] } }, { io, configPath: "memory/config", now: () => now, resolveCredentials: async id => ({ value: id === "nanogpt" ? "sk-nano-mgmt-fixture" : "fixture-key" }), resolveEnvironment: () => undefined, fetch: async (url, options) => {
 calls.push({ url, options });
 if (rateLimit) return { ok: false, status: 429, headers: { get: () => "120" } };
 const body = url.includes("synthetic") ? { subscription: { requests: 1, limit: 10, renewsAt: new Date(reset).toISOString() } } : url.includes("nano-gpt") ? quota : { data: { limits: [{ type: "TOKENS_LIMIT", unit: 3, percentage: 10 }] } };
 return { ok: true, status: 200, headers: { get: () => null }, text: async () => JSON.stringify(body) };
} });
let result = await service.refresh({ providerIds: ids, force: true });
assert.equal(calls.length, 0, "默认关闭，即使继承有效凭据也不访问网络");
assert(result.entries.every(e => e.state === "disabled"));
assert(ids.every(id => result.settings.visibility.providers[id] === false));
result = await service.save({ expectedRevision: result.settings.revision, visibility: { providers: Object.fromEntries(ids.map(id => [id, true])) } });
result = await service.refresh({ providerIds: ids, force: true });
assert(result.entries.every(e => e.state === "ok")); assert.equal(calls.length, 3);
assert.equal(calls.find(c => c.url.includes("api.z.ai")).options.headers.authorization, "fixture-key");
assert(calls.some(c => c.url === "https://nano-gpt.com/api/management/v1/subscription/usage"));
assert(!JSON.stringify(result).includes("fixture-key"));
await service.save({ providerId: "nanogpt", expectedRevision: result.settings.revision, keyMode: "manual", keyUpdate: { action: "replace", value: "inference-fixture" } });
await service.refresh({ providerIds: ["nanogpt"], force: true });
assert.equal(calls.at(-1).url, "https://api.nano-gpt.com/api/subscription/v1/usage");
// A reset deadline must not bypass Retry-After, even for a manual refresh.
rateLimit = true; now += 1000;
await service.refresh({ providerIds: ["synthetic"], force: true });
const count = calls.length; now = reset + 1000;
result = await service.refresh({ providerIds: ["synthetic"], force: true });
assert.equal(calls.length, count); assert.equal(result.entries[0].freshness, "stale");
now += 120000; await service.refresh({ providerIds: ["synthetic"], force: true });
assert.equal(calls.length, count + 1);
service.dispose();
console.log("PASS new provider defaults, region/auth isolation, quota units, degraded data and reset backoff");
